package main

import (
	"fmt"
	"strings"
)

// Acceptance criteria of the report.
const (
	minPeakReductionPct = 15.0
	minMetMinSoCPct     = 95.0
)

var coordinatedStrategies = []string{"equal", "need", "weighted"}

func table(b *strings.Builder, head []string, rows [][]string) {
	b.WriteString("| " + strings.Join(head, " | ") + " |\n|")
	for range head {
		b.WriteString("---|")
	}
	b.WriteString("\n")
	for _, r := range rows {
		b.WriteString("| " + strings.Join(r, " | ") + " |\n")
	}
	b.WriteString("\n")
}

func yesNo(ok bool) string {
	if ok {
		return "yes"
	}
	return "**no**"
}

func clp(v float64) string {
	s := fmt.Sprintf("%.0f", v)
	neg := strings.HasPrefix(s, "-")
	s = strings.TrimPrefix(s, "-")
	var out []string
	for len(s) > 3 {
		out = append([]string{s[len(s)-3:]}, out...)
		s = s[:len(s)-3]
	}
	out = append([]string{s}, out...)
	r := strings.Join(out, ".")
	if neg {
		r = "-" + r
	}
	return r
}

// Report renders the Markdown summary of all runs and sweeps.
func Report(runs []ScenarioRun, sens []SweepRow) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }

	w("# Depot simulation results\n\n")
	w("Generated by `motor/cmd/depotsim` (do not edit by hand: re-run the simulator). Offline, deterministic " +
		"simulation of an overnight electric-bus depot comparing **uncoordinated charging** (baseline) with the " +
		"allocation strategies of the motor's engine (`equal`, `need`, `weighted` = formulas 1-9 of the report " +
		"with the contingency rule), all on the same declared inputs.\n\n")

	w("## How to reproduce\n\n```powershell\ncd motor\ngo run ./cmd/depotsim -scenario cmd/depotsim/scenarios -out ../docs/results\n```\n\n")
	w("Every input is in the scenario files listed below; the fleet of S4 and of the fleet-size sweep is drawn by " +
		"a seeded generator (same seed, same fleet). Same inputs always give the same files. " +
		"`go test ./cmd/depotsim` checks the mechanics (formula 9, taper, limit, determinism, Cuadro 9).\n\n")

	// Scenarios
	w("## Scenarios\n\n")
	var rows [][]string
	for _, r := range runs {
		s := r.Scenario
		aux := fmt.Sprintf("%.0f kW", s.AuxKW)
		if len(s.AuxProfile) > 0 {
			var p []string
			for _, a := range s.AuxProfile {
				p = append(p, fmt.Sprintf("%.0f from %s", a.KW, a.From))
			}
			aux = strings.Join(p, ", ") + " kW"
		}
		installed := float64(s.Chargers) * s.ChargerKW
		rows = append(rows, []string{s.ID, s.Title, fmt.Sprintf("%.0f kW (%.0f %%)", s.SiteLimitKW, 100*s.SiteLimitKW/installed),
			aux, fmt.Sprintf("%d x %.0f kW", s.Chargers, s.ChargerKW), fmt.Sprintf("%d", len(s.Buses)),
			fmt.Sprintf("%d min", s.IntervalMin), fmt.Sprintf("`%s`", r.File)})
	}
	table(&b, []string{"ID", "Scenario", "Site limit (% of installed)", "Auxiliary load", "Chargers", "Buses", "Δt", "Input file"}, rows)
	for _, r := range runs {
		w("- **%s**: %s\n", r.Scenario.ID, r.Scenario.Description)
	}
	w("\n")

	// Headline
	w("## Headline results\n\n")
	w("Peak = highest 1-minute site power (EV + auxiliary load). Reduction is against the uncoordinated baseline " +
		"of the same scenario. \"Min SoC met\" = departures with SoC ≥ minimum SoC. Violations = control intervals " +
		"in which the assigned power + auxiliary load, or the measured site power, exceeded the site limit.\n\n")
	rows = nil
	for _, r := range runs {
		s := r.Scenario
		u := r.Results[Uncoordinated].Metrics
		row := []string{s.ID, fmt.Sprintf("%.0f", s.SiteLimitKW), f1(u.PeakKW)}
		for _, st := range coordinatedStrategies {
			row = append(row, f1(r.Results[st].Metrics.PeakKW))
		}
		row = append(row, f1(reduction(u.PeakKW, r.Results["weighted"].Metrics.PeakKW)))
		for _, st := range Strategies {
			m := r.Results[st].Metrics
			row = append(row, f1(pct(m.MetMin, m.Departures)))
		}
		var v []string
		for _, st := range Strategies {
			v = append(v, fmt.Sprint(r.Results[st].Metrics.LimitViol))
		}
		row = append(row, strings.Join(v, " / "))
		rows = append(rows, row)
	}
	table(&b, []string{"Scen.", "Limit kW", "Peak uncoord. kW", "Peak equal kW", "Peak need kW", "Peak weighted kW",
		"Reduction weighted %", "Min SoC met % uncoord.", "equal", "need", "weighted", "Violations (unc / equal / need / weighted)"}, rows)

	// Acceptance criteria
	w("## Acceptance criteria\n\n")
	w("Criteria of the report: peak reduction ≥ %.0f %% against uncoordinated charging, ≥ %.0f %% of departures with "+
		"SoC ≥ minimum, and the assigned total never above the site limit in any control interval.\n\n",
		minPeakReductionPct, minMetMinSoCPct)
	rows = nil
	for _, r := range runs {
		u := r.Results[Uncoordinated].Metrics
		for _, st := range coordinatedStrategies {
			m := r.Results[st].Metrics
			red := reduction(u.PeakKW, m.PeakKW)
			met := pct(m.MetMin, m.Departures)
			ok1, ok2, ok3 := red >= minPeakReductionPct, met >= minMetMinSoCPct, m.LimitViol == 0
			rows = append(rows, []string{r.Scenario.ID, st, f1(red), yesNo(ok1), f1(met), yesNo(ok2),
				fmt.Sprint(m.LimitViol), yesNo(ok3), yesNo(ok1 && ok2 && ok3)})
		}
	}
	table(&b, []string{"Scen.", "Strategy", "Peak red. %", "≥ 15 %", "Min SoC met %", "≥ 95 %", "Violations", "= 0", "All met"}, rows)
	w("The uncoordinated baseline exceeds the limit wherever its peak is above it (see violations above); it is " +
		"the reference, not a candidate.\n\n")

	// Full indicators
	w("## All indicators\n\n")
	head := []string{"Strategy", "Peak kW", "Peak 15-min kW", "Red. %", "Min SoC met %", "Target met %",
		"Lowest dep. SoC %", "Mean dep. SoC %", "Energy kWh", "Mean connection h", "Mean charging h",
		"Charger utilization", "Setpoint changes", "Violations", "Contingency bus-intervals (buses)"}
	for _, r := range runs {
		w("### %s\n\n", r.Scenario.ID)
		u := r.Results[Uncoordinated].Metrics
		rows = nil
		for _, st := range Strategies {
			m := r.Results[st].Metrics
			sp := fmt.Sprint(m.SetpointChg)
			cont := fmt.Sprintf("%d (%d)", m.ContingencyBI, m.ContingencyB)
			if st == Uncoordinated {
				sp, cont = "-", "-"
			}
			rows = append(rows, []string{st, f1(m.PeakKW), f1(m.Peak15KW), f1(reduction(u.PeakKW, m.PeakKW)),
				f1(pct(m.MetMin, m.Departures)), f1(pct(m.MetTarget, m.Departures)), f1(m.MinDepSoC), f1(m.MeanDepSoC),
				f1(m.EnergyKWh), f2(m.MeanConnectH), f2(m.MeanChargingH), f3(m.Utilization), sp,
				fmt.Sprint(m.LimitViol), cont})
		}
		table(&b, head, rows)

		// per bus
		rows = nil
		for i, bus := range r.Scenario.Buses {
			row := []string{bus.ID, fmt.Sprintf("%.0f", bus.BatteryKWh), bus.Arrival, bus.Departure,
				fmt.Sprintf("%.0f", bus.ArrivalSoC), fmt.Sprintf("%.0f / %.0f", bus.MinSoC, bus.TargetSoC), fmt.Sprint(bus.Importance)}
			for _, st := range Strategies {
				pb := r.Results[st].Metrics.PerBus[i]
				cell := f1(pb.DepSoC)
				if pb.DepSoC < pb.MinSoC-1e-6 {
					cell = "**" + cell + "**"
				}
				row = append(row, cell)
			}
			row = append(row, fmt.Sprint(r.Results["weighted"].Metrics.PerBus[i].Contingency))
			rows = append(rows, row)
		}
		w("Departure SoC per bus (bold = below the minimum):\n\n")
		table(&b, []string{"Bus", "kWh", "Arrival", "Departure", "Arr. SoC %", "Min / target %", "Imp.",
			"uncoord.", "equal", "need", "weighted", "Contingency intervals (weighted)"}, rows)
	}

	// Cuadro 9 check
	for _, r := range runs {
		if r.Scenario.ID != "C8" {
			continue
		}
		ser := r.Results["weighted"].Series
		if len(ser) == 0 {
			break
		}
		w("## Check against Cuadro 9 of the report (C8, first 10-minute interval, weighted)\n\n")
		want := map[string]string{"A": "71.4", "B": "78.7", "C": "124.6", "D": "25.2"}
		rows = nil
		for i, bus := range r.Scenario.Buses {
			rows = append(rows, []string{bus.ID, want[bus.ID], f1(ser[0].BusKW[i])})
		}
		table(&b, []string{"Bus", "Report kW", "Simulator kW (mean of the interval)"}, rows)
		w("Setpoints are floored to 100 W by the engine, hence differences of up to 0.1 kW.\n\n")
	}

	// Avoided cost
	w("## Avoided peak and avoided cost (placeholder tariffs)\n\n")
	w("**The tariff and investment values are placeholders declared in each scenario file " +
		"(`demand_charge_clp_per_kw_month`, `connection_upgrade_clp_per_kw`) and must be replaced with the " +
		"distributor's actual values; these figures are not real savings.** Avoided demand = 15-minute peak of the " +
		"baseline − 15-minute peak of the strategy (the demand charge is billed on 15-minute averages). Avoided " +
		"enlargement = baseline 1-minute peak − site limit: the connection capacity the depot would need without " +
		"coordination.\n\n")
	rows = nil
	for _, r := range runs {
		s := r.Scenario
		u := r.Results[Uncoordinated].Metrics
		m := r.Results["weighted"].Metrics
		kw, month, upKW, upCLP := avoided(s, m, u)
		rows = append(rows, []string{s.ID, clp(s.DemandChargeCLPPerKWMonth), f1(u.Peak15KW), f1(m.Peak15KW), f1(kw),
			clp(month), clp(12 * month), f1(upKW), clp(s.UpgradeCLPPerKW), clp(upCLP)})
	}
	table(&b, []string{"Scen.", "Demand charge CLP/kW-month", "Peak 15-min uncoord. kW", "Peak 15-min weighted kW",
		"Avoided demand kW", "CLP/month", "CLP/year", "Avoided enlargement kW", "Upgrade CLP/kW", "Avoided investment CLP"}, rows)

	// Sensitivity
	w("## Sensitivity\n\n")
	b.WriteString("Each sweep changes one input of the named scenario and re-runs the baseline and the strategies. Cells: " +
		"min SoC met % · lowest departure SoC % · peak reduction %.\n\n")
	type key struct{ sweep, scn string }
	var order []key
	groups := map[key][]SweepRow{}
	for _, r := range sens {
		k := key{r.Sweep, r.Scenario}
		if _, ok := groups[k]; !ok {
			order = append(order, k)
		}
		groups[k] = append(groups[k], r)
	}
	titles := map[string]string{
		"limit_kw":            "Site limit (kW)",
		"fleet_size":          "Fleet size (one charger per bus, limit fixed)",
		"urgency_weight":      "Urgency weight wU (other weights rescaled to keep their proportions and sum 1)",
		"departure_shift_min": "Departure shift (minutes added to every departure)",
		"interval_min":        "Control interval Δt (minutes)",
	}
	for _, k := range order {
		w("### %s: %s\n\n", k.scn, titles[k.sweep])
		var values []string
		cells := map[string]map[string]SweepRow{}
		var strats []string
		seen := map[string]bool{}
		for _, r := range groups[k] {
			if cells[r.Value] == nil {
				cells[r.Value] = map[string]SweepRow{}
				values = append(values, r.Value)
			}
			cells[r.Value][r.Strategy] = r
			if !seen[r.Strategy] && r.Strategy != Uncoordinated {
				seen[r.Strategy] = true
				strats = append(strats, r.Strategy)
			}
		}
		head := []string{"Value", "Peak uncoord. kW"}
		for _, st := range strats {
			head = append(head, st)
		}
		if k.sweep == "urgency_weight" {
			head = append(head, "Contingency bus-intervals", "Weights (U/D/E/I)")
		}
		rows = nil
		for _, v := range values {
			c := cells[v]
			row := []string{v, f1(c[strats[0]].BaseM.PeakKW)}
			for _, st := range strats {
				r := c[st]
				row = append(row, fmt.Sprintf("%.0f · %.1f · %.1f", pct(r.M.MetMin, r.M.Departures), r.M.MinDepSoC, r.ReductionPct()))
			}
			if k.sweep == "urgency_weight" {
				r := c["weighted"]
				ww := r.V.Weights
				row = append(row, fmt.Sprint(r.M.ContingencyBI), fmt.Sprintf("%.3f / %.3f / %.3f / %.3f", ww.Urgency, ww.Deficit, ww.Energy, ww.Importance))
			}
			rows = append(rows, row)
		}
		table(&b, head, rows)
	}

	// Assumptions
	w("## Declared assumptions\n\n")
	for _, a := range assumptions {
		w("- %s\n", a)
	}
	w("\n## Files\n\n")
	w("- `summary.csv`: every indicator per scenario and strategy (also avoided peak and cost).\n")
	w("- `buses.csv`: arrival and departure SoC, energy and contingency intervals per bus.\n")
	w("- `sensitivity.csv`: every sweep variant and strategy, same columns as `summary.csv`.\n")
	w("- `timeseries/<scenario>_<strategy>.csv`: one row per control interval: auxiliary load, power available " +
		"to the engine, assigned power, mean and maximum site power, limit, mean power and end SoC of each bus (for figures).\n")
	return b.String()
}

var assumptions = []string{
	"Time step: the physics advance in 1-minute steps; setpoints are recomputed every Δt (10 min by default) and " +
		"also when a bus connects or leaves (as the motor does); `periodic_only: true` disables the event recompute.",
	"Setpoints are held between control instants: power a bus cannot draw because its acceptance tapers or it " +
		"reaches its target mid-interval is not redistributed until the next instant (this is why strategies deliver " +
		"slightly different energy under the same limit). A bus already at its target is not passed to the engine.",
	"SoC update: formula (9), SoC' = SoC + 100·η·P·Δt/capacity, applied every minute with the power actually drawn.",
	"Power drawn by a bus = min(setpoint, charger rating, battery acceptance at the current SoC, energy left to the target). " +
		"The baseline has no setpoint: it draws min(charger, battery acceptance) from connection until it reaches the target.",
	"Battery acceptance (taper): constant maximum power up to the transition SoC (80 %), then linear down to " +
		"20 % of the maximum at 100 % SoC. Placeholder until datasheet curves are available.",
	"Charging efficiency η = 0.95 (grid → battery), constant. Energy figures are grid side unless stated.",
	"A bus stops charging at its target SoC and stays plugged in until its departure (the charger is not released " +
		"unless `release_when_full` is set). Buses are assigned to free chargers first come, first served.",
	"Available power for the engine = site limit − safety margin (0 kW here) − highest auxiliary load inside the " +
		"interval. Auxiliary load is a declared step profile, known in advance.",
	"Each session's cap passed to the engine = min(charger rating, battery acceptance now, energy to the target / Δt) " +
		"for every coordinated strategy (the weighted strategy applies the same E/Δt bound internally, formula 8). " +
		"Because of this bound, coordinated strategies differ slightly from the baseline even when the limit does not " +
		"bind (the last part of each charge is spread over more intervals): see the 1500 kW row of the limit sweep.",
	"Engine inputs: minimum power 0 W (DC chargers can modulate to zero), Pmax for the urgency = min(charger, bus max), " +
		"hours left = time to the scheduled departure, importance 1-5, weights from the scenario (report: 0.40/0.20/0.20/0.20).",
	"Peak demand = highest 1-minute site power (EV + auxiliary). The demand-charge estimate uses the highest " +
		"15-minute average on clock blocks (:00, :15, :30, :45).",
	"Charger utilization = energy delivered / (chargers × rating × hours from the first arrival to the last departure).",
	"Mean connection time counts from connection to departure; mean charging time counts minutes with power > 0.",
	"Setpoint changes = setpoints that changed by at least 100 W (the engine's granularity) at a control instant. " +
		"The baseline sends none.",
	"Contingency activations are counted when formula (7) forecasts a departure SoC below the minimum for a bus not yet at its target.",
	"Coordinated strategies use all the power available up to each bus's cap (they do not shave below the limit), " +
		"so their peak is essentially the site limit whenever the baseline would exceed it: the peak reduction is " +
		"≈ 1 − limit / uncoordinated peak, and the question the simulation answers is whether the departures are still " +
		"met under that limit.",
	"Tariffs (demand charge, connection upgrade cost) are placeholders, not real prices.",
}
